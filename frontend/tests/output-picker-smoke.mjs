import {createRequire} from "node:module";
import assert from "node:assert/strict";
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_PATH || "playwright");
const browser=await chromium.launch({headless:true,channel:"chrome"});
const page=await browser.newPage({viewport:{width:1440,height:960},reducedMotion:"reduce"});
let writes=0;
await page.route("**/api/v1/**",async route=>{
  if(route.request().method()!=="GET")writes++;
  await route.fulfill({contentType:"application/json",body:"[]"});
});
try {
  await page.goto("http://127.0.0.1:3011/");
  const trigger=page.getByRole("button",{name:"选择图片类型",exact:true});
  await trigger.waitFor();
  const before=await page.locator(".studioComposer").boundingBox();
  await trigger.click();
  const group=page.getByRole("group",{name:"单项图片类型",exact:true});
  assert.equal(await group.getByRole("button").count(),9);
  assert.equal(await group.getByRole("button",{name:"全案设计",exact:true}).count(),0);
  assert.equal(await page.locator(".studioSettings").count(),0);
  assert.equal(await page.locator("form .studioOutputPopover").count(),1);
  assert.deepEqual(await page.locator(".studioComposer").boundingBox(),before);
  await page.screenshot({path:"/tmp/tuanhui-output-picker-desktop.png"});
  await group.getByRole("button",{name:"三连图",exact:true}).click();
  assert((await trigger.textContent()).includes("三连图"));
  assert.equal(await page.locator(".studioOutputPopover").count(),0);
  await trigger.click();await page.keyboard.press("Escape");
  assert(await trigger.evaluate(el=>el===document.activeElement));
  await trigger.click();await page.getByRole("heading",{name:"今天，想为门店做什么图？"}).click();
  assert.equal(await page.locator(".studioOutputPopover").count(),0);
  await page.setViewportSize({width:375,height:812});
  await trigger.click();
  const box=await page.locator(".studioOutputPopover").boundingBox();
  assert(box.x>=0 && box.x+box.width<=375 && box.y>=0);
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:"/tmp/tuanhui-output-picker-mobile.png"});
  await page.keyboard.press("Escape");
  await page.locator(".creationTypeTabs").getByRole("button",{name:"全案设计",exact:true}).click();
  await page.waitForURL("**/full-plan");
  await page.getByRole("button",{name:"选择全案作品",exact:true}).click();
  const full=page.getByRole("group",{name:"全案包含的作品",exact:true});
  assert.equal(await full.locator('[aria-pressed="true"]').count(),3);
  await full.getByRole("button",{name:"三连图",exact:true}).click();
  assert.equal(await full.locator('[aria-pressed="true"]').count(),4);
  assert.equal(writes,0,"changing ports/options must not call a model or create a project");
  await page.screenshot({path:"/tmp/tuanhui-full-plan-shell.png"});
  console.log("PASS: single-only picker / anchored compact popup / keyboard+outside dismissal / mobile / separate full-plan route / no writes");
} finally { await browser.close(); }
